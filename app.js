// Dates below are transcribed from the supplied timetable. Dates in January belong to 2027.
function dates(list) {
  return list.split(',').map(x => {
    const [dd, mm] = x.trim().split('.').map(Number);
    const year = mm <= 8 ? 2027 : 2026;
    return `${year}-${String(mm).padStart(2, '0')}-${String(dd).padStart(2, '0')}`;
  });
}
