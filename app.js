function localISODate(date = new Date()) {
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
}
function clampDate(date, min, max) { return date < min ? min : (date > max ? max : date); }
function parseISO(iso) { const [y, m, d] = iso.split('-').map(Number); return new Date(y, m - 1, d, 12, 0, 0); }
function addDays(iso, amount) { const d = parseISO(iso); d.setDate(d.getDate() + amount); return localISODate(d); }
function dateLabel(iso) {
  const d = parseISO(iso);
  return `${DAY_NAMES[d.getDay()]}, ${d.getDate()} ${MONTH_NAMES[d.getMonth()]} ${d.getFullYear()}`;
}
function shortDayLabel(iso) { const d = parseISO(iso); return `${d.getDate()} ${MONTH_NAMES[d.getMonth()]}`; }
function escapeHTML(value) {
  return String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));
}
function typeLabel(kind) { return kind === 'elective' ? 'Факультатив' : kind === 'practice' ? 'Практика' : 'Занятие'; }
function sortTime(time) { return Number(time.slice(0, 2)) * 60 + Number(time.slice(3, 5)); }
function renderWeek() {
  weekStrip.innerHTML = '';
  const d = parseISO(selectedDate);
  const mondayOffset = (d.getDay() + 6) % 7;
  const weekStart = addDays(selectedDate, -mondayOffset);
  for (let i = 0; i < 7; i++) {
    const iso = addDays(weekStart, i);
    const day = parseISO(iso);
    if (iso < START_DATE || iso > END_DATE) {
      const spacer = document.createElement('div');
      spacer.className = 'week-day';
      spacer.style.visibility = 'hidden';
      weekStrip.appendChild(spacer);
      continue;
    }
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'week-day' + (iso === selectedDate ? ' selected' : '') + (iso === localISODate() ? ' today' : '');
    button.setAttribute('aria-label', dateLabel(iso));
    button.setAttribute('aria-pressed', String(iso === selectedDate));
    button.innerHTML = `<span class="week-name">${DAY_SHORT[day.getDay()]}</span><span class="week-number">${day.getDate()}</span>`;
    button.addEventListener('click', () => selectDate(iso));
    weekStrip.appendChild(button);
  }
}
