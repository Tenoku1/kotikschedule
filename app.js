    const groupText = item.group ? `Подгруппа № ${item.group}` : 'Для всех подгрупп';
    const card = document.createElement('article');
    card.className = 'lesson-card';
    const badgeClass = item.kind === 'elective' ? 'elective' : item.kind === 'practice' ? 'practice' : '';
